/**
 * Configuration class for the DigiCert TLM Automation Plugin (Cloudflare custom certificates).
 * <p>
 * Populated by the TLM SDK from the values entered against the connector in TLM, which map to the
 * fields declared in {@code configuration.json}.
 * <ul>
 *   <li><b>zoneId</b>: the Cloudflare zone this connector manages.</li>
 *   <li><b>password</b>: the Cloudflare <em>API token</em>. In <em>Direct input</em> mode TLM stores
 *       it encrypted and hands it over base64-encoded; in <em>Secrets manager</em> mode the operator
 *       enters a PAM vault reference and TLM injects the resolved secret into this same field at
 *       runtime. (The field keeps the name {@code password} because that is the field TLM's
 *       sensitive-credential and PAM handling is wired to.)</li>
 *   <li><b>csrMode</b>: {@code cloudflare} (key + CSR generated by Cloudflare) or {@code sensor}.</li>
 *   <li><b>csrSubjectFallback</b>: {@code C=…, ST=…, L=…, O=…} used for Cloudflare CSRs when the
 *       TLM subject DN lacks one of the attributes Cloudflare insists on.</li>
 *   <li><b>renewalStrategy</b>: {@code update} / {@code replace_delete} / {@code replace_keep}.</li>
 *   <li><b>certificateType</b>: {@code sni_custom} / {@code legacy_custom} for new uploads.</li>
 *   <li><b>bundleMethod</b>: {@code force} / {@code ubiquitous} / {@code optimal}.</li>
 *   <li><b>csrRetention</b>: how many older Cloudflare CSRs per common name to keep.</li>
 *   <li><b>authenticationMethod</b> / <b>pamConnectorId</b>: consumed by TLM to drive the UI and
 *       the secret-resolution step; the plugin reads them only for diagnostics.</li>
 * </ul>
 * <b>Important:</b> Any field added, removed, or renamed here must also be reflected in
 * {@code configuration.json} so the TLM UI maps them correctly.
 */
package com.example.automation.extended.configuration;

import com.fasterxml.jackson.annotation.JsonAlias;
import com.fasterxml.jackson.annotation.JsonIgnoreProperties;

import lombok.Data;

@Data
@JsonIgnoreProperties(ignoreUnknown = true)
public class MyPluginConfiguration {

    /** {@code authentication_method} value for a token typed directly into TLM. */
    public static final String AUTH_DIRECT = "Self authentication";

    /** {@code authentication_method} value for a token resolved via a Secrets Manager (PAM) connector. */
    public static final String AUTH_SECRETS_MANAGER = "Self authentication secrets manager";

    /** Cloudflare zone id (32 hex characters). */
    @JsonAlias({"zoneId", "zone_id", "zone", "management_ip", "managementIp"})
    private String zoneId;

    /**
     * Cloudflare API token. Direct-input mode: base64-encoded by TLM. Secrets-manager mode: the
     * resolved secret injected by the PAM connector at runtime.
     */
    @JsonAlias({"password", "authToken", "auth_token", "apiToken", "api_token", "token"})
    private String password;

    @JsonAlias({"csrMode", "csr_mode", "keySource", "key_source"})
    private String csrMode;

    @JsonAlias({"csrSubjectFallback", "csr_subject_fallback"})
    private String csrSubjectFallback;

    @JsonAlias({"renewalStrategy", "renewal_strategy"})
    private String renewalStrategy;

    @JsonAlias({"certificateType", "certificate_type"})
    private String certificateType;

    @JsonAlias({"bundleMethod", "bundle_method"})
    private String bundleMethod;

    /** As a string: TLM inputs are strings. */
    @JsonAlias({"csrRetention", "csr_retention"})
    private String csrRetention;

    @JsonAlias({"authentication_method", "authenticationMethod"})
    private String authenticationMethod;

    @JsonAlias({"pam_connector_id", "pamConnectorId"})
    private String pamConnectorId;

    /** True when the connector is configured to resolve the token through a PAM connector. */
    public boolean isSecretsManagerAuth() {
        return AUTH_SECRETS_MANAGER.equalsIgnoreCase(authenticationMethod);
    }
}
